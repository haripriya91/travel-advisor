
from pydantic import BaseModel, Field, model_validator


class TripState(BaseModel):
    """Information collected during the conversation."""

    destination: str | None = None

    duration_days: int | None = Field(
        default=None,
        ge=1,
        le=30,
    )

    interests: list[str] = Field(default_factory=list)

    preferences: list[str] = Field(default_factory=list)

    # Number of people traveling
    travelers: int | None = Field(
        default=None,
        ge=1,
        le=30,
    )

    # Example: "solo", "couple", "2 adults and 1 child"
    travel_group: str | None = None

    # Optional total budget provided by the user
    budget: float | None = Field(
        default=None,
        gt=0,
    )

    currency: str = "EUR"

    # Optional trip start date, format YYYY-MM-DD (used for weather forecasts)
    start_date: str | None = None


class Activity(BaseModel):
    time: str
    title: str
    description: str

    estimated_cost: float = Field(
        default=0,
        ge=0,
    )


class ItineraryDay(BaseModel):
    day: int = Field(ge=1)

    title: str

    activities: list[Activity] = Field(
        min_length=1,
    )


class TravelItinerary(BaseModel):
    """Structured itinerary generated by OpenAI."""

    title: str
    summary: str
    destination: str

    duration_days: int = Field(ge=1)

    days: list[ItineraryDay]

    practical_tips: list[str] = Field(
        min_length=1,
    )

    estimated_budget: float = Field(ge=0)

    currency: str = "EUR"

    # Explains what the estimated budget covers.
    # Example: "Total for 2 adults and 1 child"
    budget_basis: str

    # Added for external data (weather, transport, currency)
    weather_summary: str | None = None

    transport_tips: list[str] = Field(default_factory=list)

    currency_note: str | None = None

    @model_validator(mode="after")
    def check_day_count(self):
        """Validate the number and order of itinerary days."""

        if len(self.days) != self.duration_days:
            raise ValueError(
                "The number of itinerary days must match duration_days."
            )

        expected_days = list(
            range(1, self.duration_days + 1)
        )

        actual_days = [
            day.day for day in self.days
        ]

        if actual_days != expected_days:
            raise ValueError(
                "Itinerary days must be numbered consecutively from 1."
            )

        return self
